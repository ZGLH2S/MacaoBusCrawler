package com.albez.bus.service;

import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;

import javax.sql.DataSource;
import java.io.BufferedWriter;
import java.io.IOException;
import java.io.OutputStream;
import java.io.OutputStreamWriter;
import java.io.Reader;
import java.math.BigDecimal;
import java.math.BigInteger;
import java.nio.charset.StandardCharsets;
import java.sql.Blob;
import java.sql.Clob;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.ResultSetMetaData;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.temporal.TemporalAccessor;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;

@Service
@RequiredArgsConstructor
public class DatabaseExportService {
    private static final String[] EXPORT_TYPES = {"TABLE", "VIEW"};
    private static final char[] HEX = "0123456789ABCDEF".toCharArray();

    private final DataSource dataSource;

    public void export(OutputStream outputStream) throws IOException {
        try (Connection connection = dataSource.getConnection();
             BufferedWriter writer = new BufferedWriter(new OutputStreamWriter(outputStream, StandardCharsets.UTF_8))) {
            export(connection, writer);
        } catch (SQLException e) {
            throw new IOException("Failed to export database", e);
        }
    }

    private void export(Connection connection, BufferedWriter writer) throws SQLException, IOException {
        String databaseName = connection.getCatalog();
        if (databaseName == null || databaseName.isBlank()) {
            throw new SQLException("Current database catalog is empty");
        }

        List<DatabaseObject> databaseObjects = listDatabaseObjects(connection, databaseName);

        writer.write("-- Database dump generated by busCrawler\n");
        writer.write("-- Database: ");
        writer.write(databaseName);
        writer.write("\n\n");
        writer.write("SET NAMES utf8mb4;\n");
        writer.write("SET FOREIGN_KEY_CHECKS=0;\n\n");
        writer.write("CREATE DATABASE IF NOT EXISTS ");
        writer.write(quoteIdentifier(databaseName));
        writer.write(";\n");
        writer.write("USE ");
        writer.write(quoteIdentifier(databaseName));
        writer.write(";\n\n");

        for (DatabaseObject databaseObject : databaseObjects) {
            if (databaseObject.isTable()) {
                writeTable(connection, writer, databaseName, databaseObject.name());
            }
        }
        for (DatabaseObject databaseObject : databaseObjects) {
            if (databaseObject.isView()) {
                writeView(connection, writer, databaseName, databaseObject.name());
            }
        }

        writer.write("SET FOREIGN_KEY_CHECKS=1;\n");
        writer.flush();
    }

    private List<DatabaseObject> listDatabaseObjects(Connection connection, String databaseName) throws SQLException {
        DatabaseMetaData metaData = connection.getMetaData();
        List<DatabaseObject> databaseObjects = new ArrayList<>();
        try (ResultSet resultSet = metaData.getTables(databaseName, null, "%", EXPORT_TYPES)) {
            while (resultSet.next()) {
                databaseObjects.add(new DatabaseObject(
                        resultSet.getString("TABLE_NAME"),
                        resultSet.getString("TABLE_TYPE")
                ));
            }
        }
        databaseObjects.sort(Comparator.comparing(DatabaseObject::name));
        return databaseObjects;
    }

    private void writeTable(Connection connection, BufferedWriter writer, String databaseName, String tableName)
            throws SQLException, IOException {
        writer.write("-- Table structure for ");
        writer.write(quoteIdentifier(tableName));
        writer.write("\n");
        writer.write("DROP TABLE IF EXISTS ");
        writer.write(quoteIdentifier(tableName));
        writer.write(";\n");
        writer.write(showCreate(connection, "TABLE", databaseName, tableName));
        writer.write(";\n\n");

        writer.write("-- Table data for ");
        writer.write(quoteIdentifier(tableName));
        writer.write("\n");
        writeTableData(connection, writer, databaseName, tableName);
        writer.write("\n");
    }

    private void writeView(Connection connection, BufferedWriter writer, String databaseName, String viewName)
            throws SQLException, IOException {
        writer.write("-- View structure for ");
        writer.write(quoteIdentifier(viewName));
        writer.write("\n");
        writer.write("DROP VIEW IF EXISTS ");
        writer.write(quoteIdentifier(viewName));
        writer.write(";\n");
        writer.write(showCreate(connection, "VIEW", databaseName, viewName));
        writer.write(";\n\n");
    }

    private String showCreate(Connection connection, String objectType, String databaseName, String objectName) throws SQLException {
        String sql = "SHOW CREATE " + objectType + " " + qualifiedName(databaseName, objectName);
        try (Statement statement = connection.createStatement();
             ResultSet resultSet = statement.executeQuery(sql)) {
            if (resultSet.next()) {
                return resultSet.getString(2);
            }
        }
        throw new SQLException("Cannot get create statement for " + objectName);
    }

    private void writeTableData(Connection connection, BufferedWriter writer, String databaseName, String tableName)
            throws SQLException, IOException {
        String sql = "SELECT * FROM " + qualifiedName(databaseName, tableName);
        try (PreparedStatement statement = connection.prepareStatement(
                sql,
                ResultSet.TYPE_FORWARD_ONLY,
                ResultSet.CONCUR_READ_ONLY
        )) {
            statement.setFetchSize(Integer.MIN_VALUE);
            try (ResultSet resultSet = statement.executeQuery()) {
                ResultSetMetaData metaData = resultSet.getMetaData();
                int columnCount = metaData.getColumnCount();
                String columnNames = columnNames(metaData, columnCount);
                int rowCount = 0;

                while (resultSet.next()) {
                    writer.write("INSERT INTO ");
                    writer.write(quoteIdentifier(tableName));
                    writer.write(" (");
                    writer.write(columnNames);
                    writer.write(") VALUES (");
                    for (int index = 1; index <= columnCount; index++) {
                        if (index > 1) {
                            writer.write(", ");
                        }
                        writer.write(sqlLiteral(resultSet.getObject(index)));
                    }
                    writer.write(");\n");
                    rowCount++;
                }

                if (rowCount == 0) {
                    writer.write("-- No data\n");
                }
            }
        }
    }

    private String columnNames(ResultSetMetaData metaData, int columnCount) throws SQLException {
        StringBuilder builder = new StringBuilder();
        for (int index = 1; index <= columnCount; index++) {
            if (index > 1) {
                builder.append(", ");
            }
            builder.append(quoteIdentifier(metaData.getColumnName(index)));
        }
        return builder.toString();
    }

    private String sqlLiteral(Object value) throws SQLException, IOException {
        if (value == null) {
            return "NULL";
        }
        if (value instanceof Boolean booleanValue) {
            return booleanValue ? "1" : "0";
        }
        if (value instanceof Byte || value instanceof Short || value instanceof Integer || value instanceof Long
                || value instanceof Float || value instanceof Double || value instanceof BigDecimal || value instanceof BigInteger) {
            return value.toString();
        }
        if (value instanceof byte[] bytes) {
            return hexLiteral(bytes);
        }
        if (value instanceof Blob blob) {
            return hexLiteral(blob.getBytes(1, Math.toIntExact(blob.length())));
        }
        if (value instanceof Clob clob) {
            return quoteString(readClob(clob));
        }
        if (value instanceof TemporalAccessor) {
            return quoteString(value.toString());
        }
        if (value instanceof java.util.Date) {
            return quoteString(value.toString());
        }
        return quoteString(value.toString());
    }

    private String readClob(Clob clob) throws SQLException, IOException {
        try (Reader reader = clob.getCharacterStream()) {
            StringBuilder builder = new StringBuilder();
            char[] buffer = new char[4096];
            int length;
            while ((length = reader.read(buffer)) != -1) {
                builder.append(buffer, 0, length);
            }
            return builder.toString();
        }
    }

    private String quoteString(String value) {
        StringBuilder builder = new StringBuilder(value.length() + 2);
        builder.append('\'');
        for (int index = 0; index < value.length(); index++) {
            char character = value.charAt(index);
            switch (character) {
                case '\0' -> builder.append("\\0");
                case '\b' -> builder.append("\\b");
                case '\n' -> builder.append("\\n");
                case '\r' -> builder.append("\\r");
                case '\t' -> builder.append("\\t");
                case 26 -> builder.append("\\Z");
                case '\\' -> builder.append("\\\\");
                case '\'' -> builder.append("''");
                default -> builder.append(character);
            }
        }
        builder.append('\'');
        return builder.toString();
    }

    private String hexLiteral(byte[] bytes) {
        StringBuilder builder = new StringBuilder(bytes.length * 2 + 3);
        builder.append("X'");
        for (byte item : bytes) {
            builder.append(HEX[(item >> 4) & 0x0F]);
            builder.append(HEX[item & 0x0F]);
        }
        builder.append('\'');
        return builder.toString();
    }

    private String qualifiedName(String databaseName, String objectName) {
        return quoteIdentifier(databaseName) + "." + quoteIdentifier(objectName);
    }

    private String quoteIdentifier(String identifier) {
        return "`" + identifier.replace("`", "``") + "`";
    }

    private record DatabaseObject(String name, String type) {
        private boolean isTable() {
            return "TABLE".equalsIgnoreCase(type);
        }

        private boolean isView() {
            return "VIEW".equalsIgnoreCase(type);
        }
    }
}
